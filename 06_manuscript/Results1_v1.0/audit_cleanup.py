"""Inventory repository files and remove only predeclared duplicates or generated local exports."""
import argparse
import csv
import hashlib
import json
import os
from pathlib import Path
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
LOCAL = ROOT / "download_raw"
BASE = "c69f31ca2f4e9842cfe61766744b9d2b4379288f"
HISTORY = "00_project/research_records/study_development/2026-09-18/"
OLD = HISTORY + "legacy_pre_class_balanced_2026-09-18/_build_staging/"
AUTHORITY = HISTORY + "atlas_transition_2026-09-18/"
DUPLICATES = {OLD + "2026-09-18_" + name: AUTHORITY + "2026-09-18_" + name for name in (
    "Antioxidant_Mechanism_Evidence_Master.csv", "Antioxidant_Panel_Master.csv",
    "Antioxidant_Project_MASTER_Report_v1.0_CN.md")}
GENERATED = {
    "antioxidants_priority_v01.json", "Aqueous_Antioxidant_Candidate_Priority.xlsx.inspect.ndjson",
    "Assay_Specific_Rankings.xlsx.inspect.ndjson",
    *("antiox-"+name+".png" for name in ("Candidate priority", "Comparison blocks", "How to read",
      "Method coverage", "Original observations", "Within block ranks")),
}
INDEXES = {"02_identity_and_evidence/source_manifest.json", "02_identity_and_evidence/results/source_file_index.csv",
           "02_identity_and_evidence/results/source_document_index.csv", "current_review/FILE_INDEX.csv"}
FIELDS = ("path", "tracking", "action", "bytes", "sha256", "retained_copy", "reason")


def sha(p):
    return hashlib.file_digest(p.open("rb"), "sha256").hexdigest()


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT, stderr=subprocess.DEVNULL)


def paths():
    for current, dirs, files in os.walk(ROOT):
        dirs[:] = [name for name in dirs if name != ".git" and not (Path(current)/name).is_symlink()
                   and not (Path(current)/name).is_junction()]
        for name in files:
            p = Path(current)/name
            if p.is_file():
                yield p.relative_to(ROOT).as_posix()


def inventory():
    tracked = set(git("ls-files", "-z").decode().split("\0"))
    rows = []
    for path in sorted(paths()):
        p = ROOT/path
        is_tracked = path in tracked
        canonical = DUPLICATES.get(path, "")
        if canonical:
            digest = sha(p)
            assert is_tracked and canonical in tracked and digest == sha(ROOT/canonical)
            for identifier in (path, canonical):
                git("cat-file", "-e", BASE + ":" + identifier)
            references = subprocess.run(["git","grep","-Il","-F","-e",path,"-e",path.replace("/", "\\")],
                                        cwd=ROOT, capture_output=True, text=True)
            found = set(references.stdout.splitlines())
            assert references.returncode in (0, 1) and found <= INDEXES, (path, found)
            reason = "Byte-identical staging copy; baseline Git blob and original atlas copy verified; generated indexes updated."
            action = "DELETE_REDUNDANT"
        elif path in {"download_raw/"+name for name in GENERATED}:
            assert not is_tracked
            digest = sha(p)
            reason = "Disposable v0.1 workbook rendering/inspection or export payload; regenerated by prior build."
            action = "DELETE_REDUNDANT"
        else:
            digest = sha(p) if is_tracked else ""
            if path.startswith("06_manuscript/Results1_") or path in {"README.md", "current_review/README.md"}:
                action, reason = "KEEP_CURRENT", "Current release, entry or rebuild."
            elif "/frozen" in path or path.startswith("00_project/research_records/"):
                action, reason = "KEEP_HISTORICAL_REFERENCE", "Preserve distinct historical context and scientific decisions."
            elif is_tracked:
                action, reason = "KEEP_PROVENANCE", "Evidence, analysis, code, runtime specification or indexed audit trail."
            elif path.startswith(("download_raw/", ".runtime_chem/", "05_analysis/local_library/",
                                  "02_identity_and_evidence/inputs/", "02_identity_and_evidence/01_systematic_supplement/")):
                action, reason = "KEEP_PROVENANCE", "Local source material or reproduction environment."
            else:
                action, reason = "REVIEW_REQUIRED", "Unclassified local or generated asset; retained."
        rows.append(dict(path=path, tracking="TRACKED" if is_tracked else "LOCAL", action=action,
                         bytes=p.stat().st_size, sha256=digest, retained_copy=canonical, reason=reason))
    return rows


def write(path, rows):
    with path.open("w", encoding="utf8", newline="") as out:
        w = csv.DictWriter(out, fieldnames=FIELDS, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    rows = inventory()
    deleted = [r for r in rows if r["action"] == "DELETE_REDUNDANT"]
    if args.apply and not deleted:
        raise SystemExit("No eligible deletion remained. Existing audit preserved.")
    write(LOCAL / "Repository_Cleanup_Local_Inventory.csv", rows)
    write(HERE / "Repository_Cleanup_Manifest.csv", [r for r in rows
          if r["tracking"] == "TRACKED" or r["action"] == "DELETE_REDUNDANT"])
    print("Inventory",len(rows),"tracked",sum(r["tracking"]=="TRACKED" for r in rows),
          "delete",len(deleted),"review",sum(r["action"]=="REVIEW_REQUIRED" for r in rows),
          "tracked delete bytes",sum(r["bytes"] for r in deleted if r["tracking"]=="TRACKED"),
          "local delete bytes",sum(r["bytes"] for r in deleted if r["tracking"]=="LOCAL"))
    if not args.apply:
        return
    for r in deleted:
        p = (ROOT/r["path"]).resolve(strict=True)
        assert p.is_relative_to(ROOT) and p.is_file() and sha(p) == r["sha256"]
        p.unlink()
    for rel in sorted(INDEXES):
        p = ROOT/rel
        if p.suffix == ".json":
            doc = json.loads(p.read_bytes())
            doc["records"] = [r for r in doc["records"] if r["path"] not in DUPLICATES]
            p.write_text(json.dumps(doc, ensure_ascii=False, indent=2)+"\n", encoding="utf8")
        else:
            old = p.read_text(encoding="utf-8-sig")
            retained = [line for line in old.splitlines() if not any(rel_path in line for rel_path in DUPLICATES) and
                        not any("download_raw/"+name in line for name in GENERATED)]
            p.write_text("\n".join(retained)+"\n", encoding="utf8")


if __name__ == "__main__":
    main()
